package rediscache

import (
	"context"
	"fmt"
	"strconv"
	"strings"
	"sync/atomic"
	"testing"
	"time"

	redisclient "github.com/redis/go-redis/v9"
	"github.com/stretchr/testify/require"
	"github.com/stretchr/testify/suite"
)

// Redis integration methods share one server, so identical production key
// names need separate per-test namespaces. Each fixture borrows the container
// connection options and creates its own client with a prefix derived from
// the test name, local nanoseconds and an atomic sequence. Repeated fixture
// creation therefore addresses separate keys even within the same test.
//
// Hooks rewrite recognized key positions, preserving script arguments and
// string versus byte-slice representations. Unsupported commands require
// caller-supplied namespacing. Cleanup scans through the unprefixed container
// client, then unlinks this fixture's stored keys before closing its client;
// applying the fixture hook again could alter already-resolved cleanup keys.

// integrationRedis supplies the container connection options, while
// redisNamespaceSeq adds an atomic discriminator to per-test prefixes so
// repeated fixture creation keeps separate key namespaces.
var (
	// integrationRedis is initialized by TestMain and kept open until the
	// integration process finishes; testRedis borrows its connection options for
	// per-test clients.
	integrationRedis *redisclient.Client // shared integration container client
	// redisNamespaceSeq advances atomically when creating fixture clients so
	// repeated test names at nearby times receive distinct namespace prefixes.
	redisNamespaceSeq uint64 // atomic fixture namespace counter
)

// prefixHook rewrites supported Redis key arguments into one integration-test
// namespace.
type prefixHook struct {
	// prefix is generated by testRedis and reused for command rewriting and
	// cleanup matching; command arguments already bearing it stay unchanged.
	prefix string // per-test Redis key namespace
}

// IntegrationRedisSuite supplies namespaced Redis storage and assertions for
// embedded integration suites.
type IntegrationRedisSuite struct {
	suite.Suite // embedded testify assertion suite
	// ctx and rdb are initialized together by SetupTest before each suite
	// method; testRedis registers cleanup of the client's prefixed keys and
	// connection.
	ctx context.Context     // test command execution context
	rdb *redisclient.Client // namespaced Redis fixture client
}

// testRedis returns a new client using the integration container's connection
// options and a generated test key prefix. Cleanup registered on t unlinks
// that prefix's keys and closes this client.
//
// The prefix combines the sanitized test name, local nanoseconds and an
// atomic sequence to separate repeated fixture construction. Hooks modify
// only known key argument positions, including script KEYS and SCAN MATCH;
// callers using unsupported commands supply their own namespacing. Cleanup
// uses the unprefixed container client so its scan pattern and unlink
// arguments reach the stored keys directly.
func testRedis(t *testing.T) *redisclient.Client {
	t.Helper()

	prefix := fmt.Sprintf(
		"it:%s:%d:%d:",
		sanitizeRedisNamespace(t.Name()),
		time.Now().UnixNano(),
		atomic.AddUint64(&redisNamespaceSeq, 1),
	)

	opts := *integrationRedis.Options()
	rdb := redisclient.NewClient(&opts)
	rdb.AddHook(prefixHook{prefix: prefix})

	// Use the unprefixed container client for scanning and unlinking this
	// namespace so fixture hooks cannot prefix already-resolved stored keys
	// during cleanup.
	t.Cleanup(func() {
		ctx := context.Background()

		var cursor uint64
		for {
			// The count is a cursor-work hint for namespace cleanup.
			keys, nextCursor, err := integrationRedis.Scan(ctx, cursor, prefix+"*", 500).Result()
			require.NoError(t, err, "scan redis keys for cleanup")
			if len(keys) > 0 {
				require.NoError(t, integrationRedis.Unlink(ctx, keys...).Err(), "unlink redis keys for cleanup")
			}

			cursor = nextCursor
			if cursor == 0 {
				break
			}
		}

		// Close the per-test connection after unlinking its keys; teardown discards
		// the close error while key cleanup failures remain test assertions.
		_ = rdb.Close()
	})

	return rdb
}

// assertTTLWithin checks a fixture key's lifetime against inclusive duration
// limits.
func assertTTLWithin(t *testing.T, ttl time.Duration, min, max time.Duration) {
	t.Helper()
	require.GreaterOrEqual(t, ttl, min, "ttl should be >= min")
	require.LessOrEqual(t, ttl, max, "ttl should be <= max")
}

// sanitizeRedisNamespace replaces test-name slashes and spaces with
// underscores for key-prefix construction. Remaining characters pass through
// unchanged, so this helper does not escape arbitrary Redis glob patterns.
func sanitizeRedisNamespace(name string) string {
	name = strings.ReplaceAll(name, "/", "_")
	name = strings.ReplaceAll(name, " ", "_")
	return name
}

// DialHook passes the integration client's connection hook through without
// altering dialing.
func (h prefixHook) DialHook(next redisclient.DialHook) redisclient.DialHook { return next }

// ProcessHook prefixes supported command key arguments before invoking the
// next client hook. It forwards the next hook's result, while prefixCmd keeps
// already-prefixed keys from gaining the prefix twice.
func (h prefixHook) ProcessHook(next redisclient.ProcessHook) redisclient.ProcessHook {
	return func(ctx context.Context, cmd redisclient.Cmder) error {
		h.prefixCmd(cmd)
		return next(ctx, cmd)
	}
}

// ProcessPipelineHook prefixes supported key arguments in every queued
// command before the pipeline reaches the next hook. It forwards that hook's
// result and uses the same namespace rules as individual commands.
func (h prefixHook) ProcessPipelineHook(next redisclient.ProcessPipelineHook) redisclient.ProcessPipelineHook {
	return func(ctx context.Context, cmds []redisclient.Cmder) error {
		for _, cmd := range cmds {
			h.prefixCmd(cmd)
		}
		return next(ctx, cmds)
	}
}

// prefixCmd rewrites key arguments recognized by this integration fixture
// while retaining command values and unsupported argument types. Keys already
// starting with this prefix and empty key arguments pass through unchanged.
//
// Single-key commands use their first argument, MGET and deletion commands
// use all key arguments, and EVAL forms use the declared KEYS count. SCAN
// prefixes its MATCH pattern. Strings stay strings and byte slices stay byte
// slices, keeping the go-redis command representation usable after rewriting.
// Unsupported command names are left for their callers to namespace.
func (h prefixHook) prefixCmd(cmd redisclient.Cmder) {
	args := cmd.Args()
	if len(args) < 2 {
		return
	}

	prefixOne := func(i int) {
		if i < 0 || i >= len(args) {
			return
		}

		// Keep string and byte-slice keys in their command argument representation
		// while adding the namespace, so the next hook can use the existing
		// command.
		switch v := args[i].(type) {
		case string:
			if v != "" && !strings.HasPrefix(v, h.prefix) {
				args[i] = h.prefix + v
			}
		case []byte:
			s := string(v)
			if s != "" && !strings.HasPrefix(s, h.prefix) {
				args[i] = []byte(h.prefix + s)
			}
		}
	}

	switch strings.ToLower(cmd.Name()) {
	// Rewrite the first key argument for these supported single-key commands so
	// fixture setup and subsequent reads address the same test-owned Redis data.
	case "get", "getdel", "set", "setnx", "setex", "psetex", "incr", "decr", "incrby", "expire", "pexpire", "ttl", "pttl",
		"hgetall", "hget", "hset", "hdel", "hincrbyfloat", "exists",
		"zadd", "zcard", "zrange", "zrangebyscore", "zrem", "zremrangebyscore", "zrevrange", "zrevrangebyscore", "zscore":
		prefixOne(1)
	// Prefix each MGET key individually because one batch result must retain the
	// original order of values requested inside this test namespace.
	case "mget":
		for i := 1; i < len(args); i++ {
			prefixOne(i)
		}
	// Namespace every deletion key so a test's cleanup command cannot directly
	// target identically named keys belonging to another fixture.
	case "del", "unlink":
		for i := 1; i < len(args); i++ {
			prefixOne(i)
		}
	// Use the script's declared key count to prefix KEYS while leaving source,
	// hash and ARGV values intact for the same Lua behavior.
	case "eval", "evalsha", "eval_ro", "evalsha_ro":
		if len(args) < 3 {
			return
		}
		numKeys, err := strconv.Atoi(fmt.Sprint(args[2]))
		if err != nil || numKeys <= 0 {
			return
		}
		for i := 0; i < numKeys && 3+i < len(args); i++ {
			prefixOne(3 + i)
		}
	// Prefix SCAN's MATCH pattern so cursor traversal still uses Redis's command
	// shape while filtering keys to the fixture namespace.
	case "scan":
		for i := 2; i+1 < len(args); i++ {
			if strings.EqualFold(fmt.Sprint(args[i]), "match") {
				prefixOne(i + 1)
				break
			}
		}
	}
}

// SetupTest supplies a background command context and a fresh namespaced
// Redis client for the next suite method. The fixture registers cleanup with
// that method's testing.T.
func (s *IntegrationRedisSuite) SetupTest() {
	s.ctx = context.Background()
	s.rdb = testRedis(s.T())
}

// RequireNoError marks its caller as the assertion site and checks the
// supplied error.
func (s *IntegrationRedisSuite) RequireNoError(err error, msgAndArgs ...any) {
	s.T().Helper()
	require.NoError(s.T(), err, msgAndArgs...)
}

// AssertTTLWithin checks an inclusive fixture lifetime range with the caller
// marked as the assertion site.
func (s *IntegrationRedisSuite) AssertTTLWithin(ttl, min, max time.Duration) {
	s.T().Helper()
	assertTTLWithin(s.T(), ttl, min, max)
}
