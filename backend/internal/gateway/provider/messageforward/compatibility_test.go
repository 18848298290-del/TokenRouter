package messageforward

import (
	"testing"

	"github.com/stretchr/testify/require"
)

// TestIsCountTokensUnsupported404 compares counting-route errors against
// generic 404 and status-400 responses. The classifier recognizes the two
// counting-route messages and rejects empty or unrelated missing-resource
// messages.
func TestIsCountTokensUnsupported404(t *testing.T) {
	tests := []struct {
		name       string // table scenario name
		statusCode int    // upstream HTTP status
		body       string // upstream error JSON
		want       bool   // expected unsupported-route classification
	}{
		{
			name:       "exact endpoint not found",
			statusCode: 404,
			body:       `{"error":{"message":"Not found: /v1/messages/count_tokens","type":"not_found_error"}}`,
			want:       true,
		},
		{
			name:       "contains count_tokens and not found",
			statusCode: 404,
			body:       `{"error":{"message":"count_tokens route not found","type":"not_found_error"}}`,
			want:       true,
		},
		{
			name:       "generic 404",
			statusCode: 404,
			body:       `{"error":{"message":"resource not found","type":"not_found_error"}}`,
			want:       false,
		},
		{
			name:       "404 with empty error message",
			statusCode: 404,
			body:       `{"error":{"message":"","type":"not_found_error"}}`,
			want:       false,
		},
		{
			name:       "non-404 status",
			statusCode: 400,
			body:       `{"error":{"message":"Not found: /v1/messages/count_tokens","type":"invalid_request_error"}}`,
			want:       false,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := isCountTokensUnsupported404(tt.statusCode, []byte(tt.body))
			require.Equal(t, tt.want, got)
		})
	}
}
