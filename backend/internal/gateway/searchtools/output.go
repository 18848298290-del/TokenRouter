package searchtools

import (
	"encoding/json"
	"fmt"
	"time"

	"github.com/TokenFlux/TokenRouter/internal/search/contract"
)

// External search output becomes one Anthropic-shaped message with a server
// call, its result block and readable summary. Call/result blocks share a
// reserved tool identifier so later history filtering can recognize this
// synthetic origin.
//
// Streaming opens and closes fixed indexes before terminal events, stopping on
// the first write error while still reaching Flush. JSON creates the same
// three content blocks together. Both formats report a truncated summary-byte
// estimate on the wire, while Result retains zero TokenUsage and
// injected-clock duration. Output adapters define write and delivery behavior,
// and successful builders require generated strings long enough for the
// sixteen-byte tool-ID slice.

// writeStream emits the paired search call/results and summary, then flushes
// once. Callers provide response/output and a usable identifier generator
// returning at least sixteen bytes for its tool IDs.
//
// The first failed event is observed and suppresses later block or terminal
// events. That output error is not returned after search success; Result
// retains model/duration with zero TokenUsage. Block indexes stay zero, one
// and two, and terminal wire usage estimates summary bytes rather than vendor
// measurements. The observer and output adapter own handling of any write or
// delivery failure.
func (s *Emulator) writeStream(
	output Output, query string, resp *contract.SearchResponse, model string, startTime time.Time,
) (*Result, error) {
	msgID := webSearchMsgIDPrefix + s.newID()
	// Reserve the prefix and sixteen generated bytes for synthetic-history recognition.
	toolUseID := ToolUseIDPrefix + s.newID()[:16]
	textSummary := BuildTextSummary(query, resp.Results)

	output.StartStream()
	w := output
	for _, fn := range []func() error{
		func() error { return writeSSEMessageStart(w, msgID, model) },
		func() error { return writeSSEServerToolUse(w, toolUseID, query, 0) },
		func() error { return writeSSEToolResult(w, toolUseID, resp.Results, 1) },
		func() error { return writeSSETextBlock(w, textSummary, 2) },
		// Display estimates count summary bytes and truncate fractional quarters.
		func() error { return writeSSEMessageEnd(w, len(textSummary)/tokenEstimateDivisor) },
	} {
		if err := fn(); err != nil {
			// Search already completed; stop later events after this output error while
			// retaining the execution result's zero token measurement for the caller.
			s.observe(Event{Kind: "write_failed", Err: err})
			break
		}
	}
	// Complete the adapter's buffering even after a failed event. Flush supplies
	// no additional token measurement or evidence that the client received the response.
	output.Flush()

	return &Result{Model: model, Duration: s.now().Sub(startTime)}, nil
}

// writeSSEMessageStart emits the synthetic header with empty content and zero
// initial wire usage. The caller supplies identity/model spelling and stops
// the larger sequence if this event returns an error.
func writeSSEMessageStart(w Output, msgID, model string) error {
	evt := map[string]any{
		"type": "message_start",
		"message": map[string]any{
			"id": msgID, "type": "message", "role": "assistant", "model": model,
			"content": []any{}, "stop_reason": nil, "stop_sequence": nil,
			"usage": map[string]int{"input_tokens": 0, "output_tokens": 0},
		},
	}
	return flushSSEJSON(w, "message_start", evt)
}

// writeSSEServerToolUse emits start and stop for a server search call using
// the supplied index, query and tool ID. Start failure prevents its matching
// stop and ends the caller's larger sequence.
func writeSSEServerToolUse(w Output, toolUseID, query string, index int) error {
	start := map[string]any{
		"type": "content_block_start", "index": index,
		"content_block": map[string]any{
			"type": "server_tool_use", "id": toolUseID,
			"name": toolNameWebSearch, "input": map[string]string{"query": query},
		},
	}
	if err := flushSSEJSON(w, "content_block_start", start); err != nil {
		return err
	}
	return flushSSEJSON(w, "content_block_stop", map[string]any{"type": "content_block_stop", "index": index})
}

// writeSSEToolResult emits a complete results block linked to toolUseID at
// index. Start failure prevents its stop, and BuildSearchResultBlocks retains
// the supplied result order for that event payload.
func writeSSEToolResult(w Output, toolUseID string, results []contract.SearchResult, index int) error {
	start := map[string]any{
		"type": "content_block_start", "index": index,
		"content_block": map[string]any{
			"type": "web_search_tool_result", "tool_use_id": toolUseID,
			"content": BuildSearchResultBlocks(results),
		},
	}
	if err := flushSSEJSON(w, "content_block_start", start); err != nil {
		return err
	}
	return flushSSEJSON(w, "content_block_stop", map[string]any{"type": "content_block_stop", "index": index})
}

// writeSSETextBlock emits start, summary delta and stop at the supplied index.
// Each error ends this helper immediately, allowing the owning builder to stop
// its larger message sequence.
func writeSSETextBlock(w Output, text string, index int) error {
	if err := flushSSEJSON(w, "content_block_start", map[string]any{
		"type": "content_block_start", "index": index,
		"content_block": map[string]any{"type": "text", "text": ""},
	}); err != nil {
		return err
	}
	if err := flushSSEJSON(w, "content_block_delta", map[string]any{
		"type": "content_block_delta", "index": index,
		"delta": map[string]string{"type": "text_delta", "text": text},
	}); err != nil {
		return err
	}
	return flushSSEJSON(w, "content_block_stop", map[string]any{"type": "content_block_stop", "index": index})
}

// writeSSEMessageEnd emits end_turn delta with an output estimate, then
// message_stop. Delta failure prevents the final stop; that estimate is wire
// presentation and supplies no measured vendor token evidence.
func writeSSEMessageEnd(w Output, outputTokens int) error {
	if err := flushSSEJSON(w, "message_delta", map[string]any{
		"type":  "message_delta",
		"delta": map[string]any{"stop_reason": "end_turn", "stop_sequence": nil},
		"usage": map[string]int{"output_tokens": outputTokens},
	}); err != nil {
		return err
	}
	return flushSSEJSON(w, "message_stop", map[string]string{"type": "message_stop"})
}

// flushSSEJSON serializes one event and passes its named bytes to WriteEvent.
// Encoding errors retain the marshal diagnostic prefix, and output errors
// return to the stream builder for sequence termination.
func flushSSEJSON(w Output, event string, data any) error {
	body, err := json.Marshal(data)
	if err != nil {
		return fmt.Errorf("marshal: %w", err)
	}
	return w.WriteEvent(event, body)
}

// writeJSON emits paired search call/results and summary in one synthetic
// message. Callers provide response/output and a generator returning at least
// sixteen bytes; its WriteJSON callback has no error result.
//
// Wire output estimates summary bytes divided by four and reports zero input
// tokens, while structured Result leaves TokenUsage zero. Marshal failure
// returns no result. After callback invocation the result carries model and
// injected-clock duration, supplying no proof of client receipt. Reserved tool
// IDs remain recognizable when those blocks appear in later request history.
func (s *Emulator) writeJSON(
	output Output, query string, resp *contract.SearchResponse, model string, startTime time.Time,
) (*Result, error) {
	msgID := webSearchMsgIDPrefix + s.newID()
	// Reserve the prefix and sixteen generated bytes for synthetic-history recognition.
	toolUseID := ToolUseIDPrefix + s.newID()[:16]
	textSummary := BuildTextSummary(query, resp.Results)

	msg := map[string]any{
		"id": msgID, "type": "message", "role": "assistant", "model": model,
		"content": []any{
			map[string]any{
				"type": "server_tool_use", "id": toolUseID,
				"name": toolNameWebSearch, "input": map[string]string{"query": query},
			},
			map[string]any{
				"type": "web_search_tool_result", "tool_use_id": toolUseID,
				"content": BuildSearchResultBlocks(resp.Results),
			},
			map[string]any{"type": "text", "text": textSummary},
		},
		"stop_reason": "end_turn", "stop_sequence": nil,
		// Display estimates count summary bytes and truncate fractional quarters.
		"usage": map[string]int{"input_tokens": 0, "output_tokens": len(textSummary) / tokenEstimateDivisor},
	}

	body, err := json.Marshal(msg)
	if err != nil {
		return nil, fmt.Errorf("web search emulation: marshal response: %w", err)
	}
	output.WriteJSON(body)

	return &Result{Model: model, Duration: s.now().Sub(startTime)}, nil
}
