// worker.go processes leased creative tasks through provider execution, result
// recording, and funds recovery.
// Creative queue processing owns an active lease and a separate job lock while
// provider work progresses. User and provider capacity are acquired before the
// task enters running, and their release precedes output recording and funding
// settlement after generation returns. A temporary capacity shortage leaves
// the task queued for a short requeue instead of consuming an execution
// failure attempt.
//
// Heartbeat checks queue ownership and renews supported job locks; uncertain
// or replaced ownership sets a shared loss flag and cancels processing. The
// queue loop joins that heartbeat before deciding acknowledgment or requeue.
// Recorded provider outcomes and completed legacy output metadata resume
// settlement on later attempts, while transient input loss before execution
// follows funds release. Terminal rows are acknowledged directly, so in-flight
// cancelled-success handling and later terminal-row recovery follow different
// paths.

// These defaults govern reserve waits, processing locks, recovery polling,
// and delayed retry actions. NormalizeCreativeWorkerOptions replaces each
// nonpositive option so constructed workers have positive operating budgets.
const (
	DefaultCreativeWorkerLockTTL             = 5 * time.Minute  // processing lock ownership lifetime
	DefaultCreativeWorkerLockConflictDelay   = 5 * time.Second  // job lock conflict requeue delay
	DefaultCreativeWorkerErrorRetryDelay     = time.Minute      // failed processing recovery delay
	DefaultCreativeWorkerRequeueDelay        = 30 * time.Second // unspecified pending work requeue delay
	DefaultCreativeWorkerDelayedPollInterval = 5 * time.Second  // delayed task polling interval
	DefaultCreativeWorkerRecoveryInterval    = 5 * time.Minute  // stale task recovery polling interval
	DefaultCreativeWorkerStaleActiveAfter    = 10 * time.Minute // active heartbeat age recovery threshold
	DefaultCreativeWorkerDelayedMoveLimit    = 100              // maximum due delayed batch entries
	DefaultCreativeWorkerRecoverLimit        = 100              // maximum stale active batch entries
	DefaultCreativeWorkerErrorBackoff        = time.Second      // queue loop error wait duration
	DefaultCreativeWorkerReserveBlockTimeout = 5 * time.Second  // ready reservation wait budget
	DefaultCreativeConcurrencyRequeueDelay   = time.Second      // capacity shortage requeue delay

	defaultCreativeMaxAttempts = 3 // retryable execution failure limit
)

// ErrCreativeExecutionPending requests a short requeue when concurrency
// admission is temporarily unavailable.
var ErrCreativeExecutionPending = errors.New("creative execution is pending concurrency admission")

// CreativeOutput aliases the shared indexed image bytes and MIME returned by
// platform execution.
type CreativeOutput = upstream.ImageOutput

// CreativeExecuteResult contains the selected provider's image outputs and reported cost.
type CreativeExecuteResult struct {
	// Outputs retains image byte storage returned by platform normalization.
	// Executors keep that storage stable until worker result delivery finishes
	// recording metadata and saving the generated bytes.
	Outputs    []CreativeOutput // normalized provider image result values
	ProviderID int64            // result selected provider identifier
	// ProviderCost carries reported cost metadata; Process supplies output count
	// to Results, whose funding calculation uses the run saved price instead.
	ProviderCost float64 // reported provider cost metadata
}

// CreativeWorkerOptions controls reservation, locking, recovery intervals, and
// execution retries.
type CreativeWorkerOptions struct {
	ReserveBlockTimeout time.Duration // ready reserve wait budget
	JobLockTTL          time.Duration // processing job lock lifetime
	LockConflictDelay   time.Duration // job lock conflict requeue delay
	DefaultRequeueDelay time.Duration // pending result default requeue delay
	ErrorRetryDelay     time.Duration // failed processing recovery delay
	ErrorBackoff        time.Duration // queue loop error sleep duration
	DelayedPollInterval time.Duration // empty delayed batch polling interval
	RecoveryInterval    time.Duration // stale active recovery polling interval
	StaleActiveAfter    time.Duration // maximum fresh active heartbeat age
	DelayedMoveLimit    int           // maximum delayed transfer batch entries
	RecoverLimit        int           // maximum stale recovery batch entries
	// MaxAttempts stops retryable preparation or execution failures after this
	// many increments. Settlement uses twice this count for warnings, not a
	// stop limit.
	MaxAttempts int // retryable execution failure limit
}

// CreativeProcessResult requests acknowledgment when Terminal is true,
// otherwise a delayed requeue.
type CreativeProcessResult struct {
	// Terminal chooses acknowledgment and makes RequeueAfter unused. Otherwise
	// runOnce uses a positive RequeueAfter or the configured default delay to
	// return this reservation to pending queue work.
	RequeueAfter time.Duration // requested pending result requeue delay
	Terminal     bool          // queue acknowledgment requested flag
}

// CreativeRunWorker reserves and locks tasks, executes them, recovers funding,
// and acknowledges or requeues
// them.
type CreativeRunWorker struct {
	// queue, repo, store, executor, service, ports, and opts are bound at
	// construction and shared by parallel queue loops. Keep those dependencies
	// stable after startup; busy alone tracks each loop entry and exit atomically.
	queue CreativeRunQueue       // active task lease queue
	repo  CreativeRunRepository  // task and output metadata repository
	store CreativeTransientStore // temporary task input byte storage
	// provider admission and execution implementation
	executor CreativeRunExecutor
	service  *Results              // result and funds recovery service
	ports    WorkerPorts           // stable worker admission callbacks
	opts     CreativeWorkerOptions // normalized worker operating limits
	// busy counts concurrent Process calls made through this worker's queue loop.
	busy atomic.Int32 // active queue Process call count
}

// creativeLeaseStateKey identifies the queue ownership loss state carried by a
// Process context.
type creativeLeaseStateKey struct{}

// creativeLeaseState shares heartbeat loss notification with the queue
// processing attempt.
type creativeLeaseState struct {
	// lost is set by heartbeat before processing cancellation. Process checks it
	// after provider execution returns, before recording the returned image result.
	lost atomic.Bool // heartbeat ownership loss observed flag
}

// ExecutionTarget executes requests using the selected provider's bound
// credentials and platform transport.
type ExecutionTarget interface {
	// Execute calls one prepared platform attempt using supplied run and
	// transient payload. The caller holds provider capacity and releases it after
	// the call; errors remain available for worker retry classification.
	Execute(context.Context, CreativeRun, CreativeRunPayload) (*CreativeExecuteResult, error)
}

// CreativeExecution binds an admitted provider, fixed model, execution target,
// and release callback.
type CreativeExecution struct {
	// Platform, ProviderID, UpstreamModel, and Target identify the prepared attempt.
	// The worker owns ReleaseFunc after preparation and releases provider capacity
	// with its user slot when generation ends or preparation exits early.
	Platform      string          // prepared execution provider platform
	ProviderID    int64           // prepared execution provider identifier
	UpstreamModel string          // fixed prepared upstream image model
	Target        ExecutionTarget // bound platform attempt execution
	ReleaseFunc   func()          // optional admitted provider slot release
}

// CreativeRunExecutor prepares provider admission and classifies failures for
// creative worker retries.
type CreativeRunExecutor interface {
	// Prepare validates current group rules and admits a compatible provider for
	// the run. Successful preparation transfers optional provider cleanup to the
	// caller, while ErrCreativeExecutionPending requests a short capacity retry.
	Prepare(context.Context, CreativeRun) (*CreativeExecution, error)
	// IsRetryable reports whether an execution failure can consume another
	// bounded worker attempt. Nonretryable errors enter release recovery, while
	// retryable failures increment the saved run execution counter before
	// requeue.
	IsRetryable(error) bool
}

// WorkerPorts supplies user concurrency admission and diagnostics to creative
// worker processing.
type WorkerPorts struct {
	// optional user capacity admission callback
	// AcquireUser optionally reads current user capacity. A successful acquired
	// result transfers its release callback to the worker slot lease, while
	// a false result requests requeue before provider selection or running state.
	AcquireUser func(context.Context, int64) (func(), bool, error)
	// UserMissing optionally classifies an AcquireUser error as deleted user
	// state. That result selects terminal handling instead of a generic
	// processing error returned for later requeue.
	UserMissing func(error) bool // optional missing user error classifier
	// Observe receives diagnostics from independent queue and heartbeat calls.
	// A nil callback skips reporting; configured observers support concurrent
	// invocation after worker startup.
	Observe func(string, ...any) // optional worker diagnostic callback
}

// NormalizeCreativeWorkerOptions returns operating limits with each
// nonpositive value replaced by its corresponding default. Positive durations
// and counts are retained, including values shorter than the heartbeat
// one-second floor.
func NormalizeCreativeWorkerOptions(opts CreativeWorkerOptions) CreativeWorkerOptions {
	if opts.ReserveBlockTimeout <= 0 {
		opts.ReserveBlockTimeout = DefaultCreativeWorkerReserveBlockTimeout
	}
	if opts.JobLockTTL <= 0 {
		opts.JobLockTTL = DefaultCreativeWorkerLockTTL
	}
	if opts.LockConflictDelay <= 0 {
		opts.LockConflictDelay = DefaultCreativeWorkerLockConflictDelay
	}
	if opts.DefaultRequeueDelay <= 0 {
		opts.DefaultRequeueDelay = DefaultCreativeWorkerRequeueDelay
	}
	if opts.ErrorRetryDelay <= 0 {
		opts.ErrorRetryDelay = DefaultCreativeWorkerErrorRetryDelay
	}
	if opts.ErrorBackoff <= 0 {
		opts.ErrorBackoff = DefaultCreativeWorkerErrorBackoff
	}
	if opts.DelayedPollInterval <= 0 {
		opts.DelayedPollInterval = DefaultCreativeWorkerDelayedPollInterval
	}
	if opts.RecoveryInterval <= 0 {
		opts.RecoveryInterval = DefaultCreativeWorkerRecoveryInterval
	}
	if opts.StaleActiveAfter <= 0 {
		opts.StaleActiveAfter = DefaultCreativeWorkerStaleActiveAfter
	}
	if opts.DelayedMoveLimit <= 0 {
		opts.DelayedMoveLimit = DefaultCreativeWorkerDelayedMoveLimit
	}
	if opts.RecoverLimit <= 0 {
		opts.RecoverLimit = DefaultCreativeWorkerRecoverLimit
	}
	if opts.MaxAttempts <= 0 {
		opts.MaxAttempts = defaultCreativeMaxAttempts
	}
	return opts
}

// NewCreativeRunWorker retains task dependencies and normalizes its operating
// options. The constructor starts no loops; callers provide usable processing
// dependencies and stable callbacks before RunOnce, Process, or runtime
// startup.
func NewCreativeRunWorker(queue CreativeRunQueue, repo CreativeRunRepository, store CreativeTransientStore, executor CreativeRunExecutor, results *Results, opts CreativeWorkerOptions, ports WorkerPorts) *CreativeRunWorker {
	return &CreativeRunWorker{queue: queue, repo: repo, store: store, executor: executor, service: results, opts: NormalizeCreativeWorkerOptions(opts), ports: ports}
}

// RunUntilStopped runs queue attempts until shared cancellation or a drain
// signal. A drain does not cancel work already processing, and a reservation
// acquired after the stop signal is requeued immediately.
//
// Queue attempt failures use the configured error backoff, whose wait observes
// both stop and cancellation. Successful pending results carry their own
// requeue delay. The loop checks stop before each attempt, while runOnce
// handles the race with a blocking reservation and owns joining its heartbeat
// before acknowledgment or requeue. This lets scale-down return unprocessed
// work while an admitted task drains.
func (w *CreativeRunWorker) RunUntilStopped(ctx context.Context, stop <-chan struct{}) {
	if w == nil {
		return
	}
	for {
		if ctx.Err() != nil || creativeWorkerStopRequested(stop) {
			return
		}
		if err := w.runOnce(ctx, stop); err != nil && ctx.Err() == nil {
			if !sleepOrCreativeWorkerStop(ctx, w.opts.ErrorBackoff, stop) {
				return
			}
		}
	}
}

// creativeWorkerStopRequested reports whether the optional drain channel has
// been closed or signaled. A nil channel reports false, and the nonblocking
// check leaves an unsignaled worker ready to reserve.
func creativeWorkerStopRequested(stop <-chan struct{}) bool {
	if stop == nil {
		return false
	}
	select {
	case <-stop:
		return true
	default:
		return false
	}
}

// sleepOrCreativeWorkerStop waits for delay, shared cancellation, or a drain
// signal and reports completed waiting. Nonpositive delay checks current stop
// state directly; the timer is stopped when the wait exits.
func sleepOrCreativeWorkerStop(ctx context.Context, delay time.Duration, stop <-chan struct{}) bool {
	if delay <= 0 {
		return ctx.Err() == nil && !creativeWorkerStopRequested(stop)
	}
	timer := time.NewTimer(delay)
	defer timer.Stop()
	select {
	case <-ctx.Done():
		return false
	case <-stop:
		return false
	case <-timer.C:
		return true
	}
}

// BusyCount returns this worker active queue-driven Process call count from
// its atomic counter. Nil workers return zero; direct Process calls outside
// runOnce are not included in this runtime snapshot.
func (w *CreativeRunWorker) BusyCount() int {
	if w == nil {
		return 0
	}
	return int(w.busy.Load())
}

// runOnce reserves one task, acquires its job lock, and chooses acknowledgment
// or requeue after processing. Missing core dependencies return directly;
// empty queue results also succeed.
//
// A reservation racing drain is requeued before job-lock acquisition. Lock
// errors or contention schedule a lock-conflict delay, and a held lock is
// released on exit. The heartbeat receives a cancellable Process context and
// loss flag, while busy surrounds that Process call. After processing,
// heartbeat stop and done are joined before the queue decision. Lost lease
// ownership suppresses acknowledgment and requeue; other processing errors use
// the recovery delay.
func (w *CreativeRunWorker) runOnce(ctx context.Context, stop <-chan struct{}) error {
	if w == nil || w.queue == nil || w.repo == nil || w.service == nil || w.executor == nil {
		return nil
	}

	reserved, err := w.queue.Reserve(ctx, w.opts.ReserveBlockTimeout)
	if errors.Is(err, ErrCreativeQueueEmpty) {
		return nil
	}
	if err != nil {
		return err
	}
	if creativeWorkerStopRequested(stop) {
		// The drain signal can arrive during the reserve wait. Return this newly
		// reserved lease immediately so a stopping loop does not begin
		// another task
		// while its replacement or remaining workers can process ready work.
		return w.queue.RequeueAfter(ctx, reserved.RunID, reserved.LeaseToken, 0)
	}

	lock, ok, err := w.queue.TryAcquireJobLock(ctx, reserved.RunID, w.opts.JobLockTTL)
	// A failed lock request still leaves this reservation active in the queue.
	// Requeue its lease before returning the acquisition error so another attempt
	// can retry processing after the configured lock-conflict delay.
	if err != nil {
		if requeueErr := w.queue.RequeueAfter(ctx, reserved.RunID, reserved.LeaseToken, w.opts.LockConflictDelay); requeueErr != nil {
			return requeueErr
		}
		return err
	}
	if !ok {
		// Reservation already installed active ownership before
		// job-lock contention.
		// Requeue this owned task so it can be tried after the lock holder
		// progresses instead of leaving it idle in the active set.
		return w.queue.RequeueAfter(ctx, reserved.RunID, reserved.LeaseToken, w.opts.LockConflictDelay)
	}
	// Release this acquired job lock after processing exits. Cleanup uses the
	// caller context and discards release errors, leaving an unsuccessful Redis
	// deletion to lock expiry rather than replacing the queue decision.
	defer func() {
		_ = lock.Release(ctx)
	}()

	// Run ownership checks beside processing under a cancellable child context.
	// The heartbeat publishes loss and cancels that context when queue or lock
	// ownership becomes false or uncertain, and this loop joins it before
	// updating queue state after Process returns.
	hbStop := make(chan struct{})
	hbDone := make(chan struct{})
	leaseLost := make(chan struct{}, 1)
	processCtx, cancelProcess := context.WithCancel(ctx)
	leaseState := &creativeLeaseState{}
	processCtx = context.WithValue(processCtx, creativeLeaseStateKey{}, leaseState)
	go w.runJobHeartbeat(processCtx, reserved.RunID, reserved.LeaseToken, lock, hbStop, hbDone, leaseLost, cancelProcess, leaseState)

	w.busy.Add(1)
	result, processErr := w.Process(processCtx, reserved.RunID)
	w.busy.Add(-1)
	// Stop and join heartbeat before choosing the lease queue update. Waiting
	// for done also publishes any loss notification, so late ownership checks
	// cannot race the acknowledgment or requeue decision for this attempt.
	close(hbStop)
	<-hbDone
	cancelProcess()
	select {
	case <-leaseLost:
		// A lost or uncertain lease cannot choose another queue update for this
		// reservation. Leave acknowledgment and requeue to the matching owner or
		// stale recovery rather than submitting the old token after processing.
		return ErrCreativeLeaseLost
	default:
	}
	if processErr != nil {
		w.warn("creative.worker_process_failed",
			"run_id", reserved.RunID,
			"error", processErr,
		)
		return w.queue.RequeueAfter(ctx, reserved.RunID, reserved.LeaseToken, w.opts.ErrorRetryDelay)
	}
	if result.Terminal {
		return w.queue.Ack(ctx, reserved.RunID, reserved.LeaseToken)
	}
	delay := result.RequeueAfter
	if delay <= 0 {
		delay = w.opts.DefaultRequeueDelay
	}
	return w.queue.RequeueAfter(ctx, reserved.RunID, reserved.LeaseToken, delay)
}

// Process executes one internal task or resumes its recorded funding recovery
// and returns a queue decision. Missing rows and existing terminal rows
// request acknowledgment; callers supply usable dependencies and a lease-aware
// context when invoked through the queue.
//
// Release and settlement states resume funds actions before input loading.
// Completed legacy output metadata can restore provider success. Inputs
// missing or corrupt before generation select result loss and release, while
// transient outages return an error for requeue. User then provider capacity
// is acquired before running and execution identity are written. Generation
// releases both capacities before durable result recording. Confirmed result
// persistence is retried from in-memory bytes, while an already recorded
// provider fact defers settlement to recovery instead of submitting generation
// again.
func (w *CreativeRunWorker) Process(ctx context.Context, runID string) (CreativeProcessResult, error) {
	run, err := w.repo.GetCreativeRunByRunID(ctx, runID)
	if err != nil {
		if errors.Is(err, ErrCreativeRunNotFound) {
			// A deleted task can be acknowledged and removed from the queue.
			return CreativeProcessResult{Terminal: true}, nil
		}
		return CreativeProcessResult{}, err
	}
	if run == nil {
		return CreativeProcessResult{}, errors.New("creative run is unavailable")
	}
	if IsTerminalCreativeRunStatus(run.Status) {
		return CreativeProcessResult{Terminal: true}, nil
	}
	// Funds recovery determines this branch result. Counter failures propagate,
	// while recovery-diagnostic writes are best effort and do not replace the
	// release error or block acknowledgment after successful release.
	if run.Status == CreativeRunStatusReleasePending {
		if err := w.service.ReleaseRun(ctx, runID); err != nil {
			if _, incErr := w.repo.IncrementCreativeRunReleaseAttempt(ctx, runID); incErr != nil {
				return CreativeProcessResult{}, incErr
			}
			_ = w.repo.SetCreativeRunReconcileError(ctx, runID, SanitizeCreativeMessage(err.Error()), time.Now().Add(w.opts.ErrorRetryDelay))
			return CreativeProcessResult{}, err
		}
		_ = w.repo.SetCreativeRunReconcileError(ctx, runID, "", time.Time{})
		return CreativeProcessResult{Terminal: true}, nil
	}
	// Settlement keeps its durable provider fact while funds or byte reads fail.
	// Diagnostics are best effort; the returned requeue delay carries recovery
	// forward even when persisting the latest diagnostic message fails.
	if IsCreativeRunSettlementPending(run.Status) {
		if err := w.service.SettleRun(ctx, runID); err != nil {
			attempts, incErr := w.repo.IncrementCreativeRunSettlementAttempt(ctx, runID)
			if incErr != nil {
				return CreativeProcessResult{}, incErr
			}
			_ = w.repo.SetCreativeRunReconcileError(ctx, runID, SanitizeCreativeMessage(err.Error()), time.Now().Add(w.opts.ErrorRetryDelay))
			// This threshold logs repeated settlement failure; it
			// does not end recovery
			// or remove already recorded provider work from the pending task.
			if attempts >= w.opts.MaxAttempts*2 {
				w.warn("creative.worker_settlement_pending_retries_exhausted",
					"run_id", runID,
					"attempts", attempts,
					"error", err,
				)
			}
			return CreativeProcessResult{RequeueAfter: w.opts.ErrorRetryDelay}, nil
		}
		_ = w.repo.SetCreativeRunReconcileError(ctx, runID, "", time.Time{})
		return CreativeProcessResult{Terminal: true}, nil
	}
	if recovered, recoverErr := w.recoverPersistedProviderResult(ctx, run); recoverErr != nil {
		return CreativeProcessResult{}, recoverErr
	} else if recovered {
		return CreativeProcessResult{Terminal: true}, nil
	}

	payload, err := w.loadPayload(ctx, runID)
	if err != nil {
		if errors.Is(err, ErrCreativeTransientUnavailable) {
			// An unavailable store does not establish that inputs
			// expired. Return the
			// read error so runOnce requeues with the recovery
			// delay while the
			// reservation and saved task can be inspected again on
			// a later attempt.
			return CreativeProcessResult{}, err
		}
		// The input cannot be loaded for generation on this path. Select
		// pre-execution result loss and release through Results so an absent or
		// malformed payload does not trigger an upstream call with
		// incomplete input.
		if markErr := w.service.MarkResultLost(ctx, runID, false); markErr != nil {
			w.warn("creative.worker_mark_result_lost_failed",
				"run_id", runID,
				"error", markErr,
			)
			return CreativeProcessResult{}, markErr
		}
		return CreativeProcessResult{Terminal: true}, nil
	}
	// User and provider capacity share a completion-owned slot lease for this
	// generation. Acquire user capacity first, requeue quickly when admission is
	// unavailable, and retain cleanup through all later preparation exits.
	slots := scheduler.NewLease(ctx, scheduler.ReleaseOnCompletion)
	defer slots.Release()
	if w.ports.AcquireUser != nil {
		release, acquired, err := w.ports.AcquireUser(ctx, run.UserID)
		if err != nil {
			if w.ports.UserMissing != nil && w.ports.UserMissing(err) {
				// A classified missing user skips execution and
				// requests terminal acknowledgment.
				// This branch discards result-loss recovery
				// errors, so that queue decision
				// does not confirm the metadata transition succeeded.
				_ = w.service.MarkResultLost(ctx, runID, false)
				return CreativeProcessResult{Terminal: true}, nil
			}
			return CreativeProcessResult{}, err
		}
		if !acquired {
			return CreativeProcessResult{RequeueAfter: DefaultCreativeConcurrencyRequeueDelay}, nil
		}
		slots.Own(release)
	}

	execution, err := w.executor.Prepare(ctx, *run)
	if errors.Is(err, ErrCreativeExecutionPending) {
		return CreativeProcessResult{RequeueAfter: DefaultCreativeConcurrencyRequeueDelay}, nil
	}
	if err != nil {
		return w.handleExecuteError(ctx, runID, err)
	}
	if execution == nil || execution.Target == nil {
		return w.handleExecuteError(ctx, runID, errors.New("creative execution provider is unavailable"))
	}

	// Register provider capacity after the user slot so the lease releases them
	// in reverse order. Explicit generation completion and deferred early-exit
	// cleanup share the same idempotent lease release operation.
	slots.Own(execution.ReleaseFunc)
	releaseSlots := slots.Release

	// Admission now owns user and provider capacity. Persist running before the
	// execution identity so the provider call can be associated with a task that
	// has passed both admission gates on this attempt.
	if err := w.service.MarkRunning(ctx, runID, 0); err != nil {
		return CreativeProcessResult{}, err
	}
	// Save the actual provider and platform before executing. Later completed
	// output metadata can use this saved identity to restore settlement if this
	// worker exits before recording the normal provider-success phase.
	if execution.ProviderID > 0 {
		if err := w.repo.SetCreativeRunExecution(ctx, runID, execution.ProviderID, execution.Platform, time.Now()); err != nil {
			return CreativeProcessResult{}, err
		}
	}
	// Reread state after admission and identity writes, before the upstream call.
	// A task made terminal in that interval can be acknowledged instead of
	// submitting generation using the earlier queued snapshot.
	current, err := w.repo.GetCreativeRunByRunID(ctx, runID)
	if err != nil {
		return CreativeProcessResult{}, err
	}
	if current == nil {
		return CreativeProcessResult{}, errors.New("creative run is unavailable")
	}
	if current.Status == CreativeRunStatusCancelled || IsTerminalCreativeRunStatus(current.Status) {
		if err := w.service.CancelRunByWorker(ctx, runID); err != nil {
			return CreativeProcessResult{}, err
		}
		return CreativeProcessResult{Terminal: true}, nil
	}

	result, err := execution.Target.Execute(ctx, *current, *payload)
	releaseSlots()
	if err != nil {
		return w.handleExecuteError(ctx, runID, err)
	}
	if leaseState, _ := ctx.Value(creativeLeaseStateKey{}).(*creativeLeaseState); leaseState != nil && leaseState.lost.Load() {
		return CreativeProcessResult{}, ErrCreativeLeaseLost
	}
	if result == nil {
		return w.handleExecuteError(ctx, runID, errors.New("creative executor returned no result"))
	}
	results := make([]ProviderOutput, 0, len(result.Outputs))
	for _, output := range result.Outputs {
		results = append(results, ProviderOutput{
			Index:   output.Index,
			Success: true,
			Bytes:   output.Bytes,
			Mime:    output.Mime,
		})
	}
	// Keep confirmed result bytes in memory while retrying outcome recording.
	// After a record error, reread the durable provider fact: if it exists,
	// requeue for settlement recovery instead of invoking generation again.
	// Without that fact, retain usable bytes and wait under the processing
	// context before another record attempt.
	for {
		_, recordErr := w.service.SucceedRun(ctx, runID, result.ProviderID, results)
		if recordErr == nil {
			break
		}
		if ctx.Err() != nil {
			return CreativeProcessResult{}, ctx.Err()
		}
		recorded, readErr := w.repo.GetCreativeRunByRunID(ctx, runID)
		if readErr == nil && recorded.ProviderResultRecordedAt != nil {
			return CreativeProcessResult{RequeueAfter: w.opts.ErrorRetryDelay}, nil
		}
		if errors.Is(readErr, ErrCreativeRunNotFound) {
			return CreativeProcessResult{}, readErr
		}
		valid := len(results) > 0
		for _, output := range results {
			if len(output.Bytes) == 0 {
				valid = false
			}
		}
		if !valid {
			return CreativeProcessResult{}, recordErr
		}
		timer := time.NewTimer(w.opts.ErrorRetryDelay)
		select {
		case <-ctx.Done():
			timer.Stop()
			return CreativeProcessResult{}, ctx.Err()
		case <-timer.C:
		}
	}
	// Attempt funds settlement after the provider fact and byte-save phase. Any
	// returned settlement error leaves that recorded outcome available for a
	// later funding recovery attempt that does not need another generation.
	if err := w.service.SettleRun(ctx, runID); err != nil {
		return CreativeProcessResult{}, err
	}
	return CreativeProcessResult{Terminal: true}, nil
}

// loadPayload returns execution metadata after reconstructing declared source
// and mask references from separate transient byte keys. Store errors propagate
// for Process to distinguish unavailable storage from unusable input.
//
// The returned LoadPayload pointer is retained and mutated: positive
// SourceCount replaces Sources, and HasMask replaces Mask after its read. Other
// fields remain as supplied by the store. Media keys contain bytes without MIME
// metadata, so short signatures supply labels for provider construction. Keep
// the returned payload and retained media stable while execution consumes them.
func (w *CreativeRunWorker) loadPayload(ctx context.Context, runID string) (*CreativeRunPayload, error) {
	if w.store == nil {
		return nil, errors.New("creative transient store is not configured")
	}
	payload, err := w.store.LoadPayload(ctx, runID)
	if err != nil {
		return nil, err
	}
	if payload.SourceCount > 0 {
		inputs, err := w.store.LoadInputs(ctx, runID, payload.SourceCount)
		if err != nil {
			return nil, err
		}
		payload.Sources = make([]CreativeInputImage, 0, len(inputs))
		// Input keys retain image bytes but no MIME field. Infer their
		// labels from
		// short signatures when rebuilding Sources so the provider
		// request has the
		// MIME needed for its inline or multipart representation.
		for _, data := range inputs {
			payload.Sources = append(payload.Sources, CreativeInputImage{Bytes: data, Mime: upstream.SniffImageMIME(data)})
		}
	}
	if payload.HasMask {
		mask, err := w.store.LoadMask(ctx, runID)
		if err != nil {
			return nil, err
		}
		payload.Mask = &CreativeInputImage{Bytes: mask, Mime: upstream.SniffImageMIME(mask)}
	}
	return payload, nil
}

// recoverPersistedProviderResult restores provider completion for a running
// task with fully nonpending output rows. At least one succeeded or
// acknowledged output and a positive saved provider ID are required.
//
// The method first marks provider success, then ensures settlement recovery
// and attempts settlement. Any of these errors propagates, leaving recorded
// state available to the normal funding path on a later Process call. A true
// result means this call completed that recovery sequence and generation can
// be skipped; other statuses and incomplete metadata return false directly.
func (w *CreativeRunWorker) recoverPersistedProviderResult(ctx context.Context, run *CreativeRun) (bool, error) {
	if w == nil || run == nil || run.Status != CreativeRunStatusRunning {
		return false, nil
	}
	outputs, err := w.repo.ListCreativeRunOutputs(ctx, run.RunID)
	if err != nil {
		return false, err
	}
	if len(outputs) == 0 {
		return false, nil
	}
	successCount := 0
	for _, output := range outputs {
		if output == nil || output.Status == CreativeRunOutputStatusPending {
			return false, nil
		}
		if output.Status == CreativeRunOutputStatusSucceeded || output.Status == CreativeRunOutputStatusAcked {
			successCount++
		}
	}
	if successCount == 0 || run.ProviderID == nil || *run.ProviderID <= 0 {
		return false, nil
	}
	// Completed legacy output metadata supplies the provider-work observation.
	// Record that fact before scheduling and attempting settlement, so a later
	// attempt can resume funds recovery through task state instead of
	// generating again.
	if err := w.repo.MarkCreativeRunProviderSucceeded(ctx, run.RunID, *run.ProviderID, time.Now()); err != nil {
		return false, err
	}
	if err := w.service.EnsureCreativeOutbox(ctx, run.RunID, CreativeRunOutboxSettle); err != nil {
		return false, err
	}
	if err := w.service.SettleRun(ctx, run.RunID); err != nil {
		return false, err
	}
	return true, nil
}

// handleExecuteError counts retryable preparation or execution failures and
// returns a requeue delay below MaxAttempts. Nonretryable or exhausted errors
// derive public error parts and enter failed release recovery.
//
// Retryable errors increment the stored counter before the budget decision;
// counter failures propagate and nonretryable errors leave that count unchanged.
// When execution cannot retry, FailRun persists and attempts the funds release
// sequence before this method returns terminal. A release error returns for
// later recovery, so queue acknowledgment cannot claim that this failed-work
// recovery completed merely because generation stopped.
func (w *CreativeRunWorker) handleExecuteError(ctx context.Context, runID string, execErr error) (CreativeProcessResult, error) {
	// Save the retryable failure count before comparing the execution budget.
	// Returning a delay from an unchanged count could let another processing
	// attempt repeat generation without consuming this failure from the limit.
	if w.executor.IsRetryable(execErr) {
		attempts, err := w.repo.IncrementCreativeRunAttempt(ctx, runID)
		if err != nil {
			return CreativeProcessResult{}, err
		}
		if attempts < w.opts.MaxAttempts {
			return CreativeProcessResult{RequeueAfter: w.opts.ErrorRetryDelay}, nil
		}
		w.warn("creative.worker_attempts_exhausted",
			"run_id", runID,
			"attempts", attempts,
			"error", execErr,
		)
	}
	code, message := creativeExecuteErrorParts(execErr)
	if err := w.service.FailRun(ctx, runID, code, message); err != nil {
		return CreativeProcessResult{}, err
	}
	return CreativeProcessResult{Terminal: true}, nil
}

// creativeExecuteErrorParts returns the persisted code and message for a
// nonnil execution error. Explicit upstream codes win, positive statuses
// generate status codes, and generic errors use PROVIDER_FAILED plus formatted
// error text. A matched CreativeUpstreamError pointer must be nonnil; a typed
// nil pointer cannot supply the code or message fields read by this helper.
func creativeExecuteErrorParts(err error) (string, string) {
	if upstreamErr, ok := errors.AsType[*CreativeUpstreamError](err); ok {
		if upstreamErr.Code != "" {
			return upstreamErr.Code, upstreamErr.Message
		}
		code := "PROVIDER_FAILED"
		if upstreamErr.StatusCode > 0 {
			code = "UPSTREAM_STATUS_" + itoaPositive(upstreamErr.StatusCode)
		}
		return code, upstreamErr.Message
	}
	return "PROVIDER_FAILED", SanitizeCreativeMessage(err.Error())
}

// itoaPositive returns decimal digits for a positive integer using an owned
// byte slice. Zero and negative values return the literal zero used when no
// positive status number can be represented.
func itoaPositive(v int) string {
	if v <= 0 {
		return "0"
	}
	digits := make([]byte, 0, 4)
	for v > 0 {
		digits = append([]byte{byte('0' + v%10)}, digits...)
		v /= 10
	}
	return string(digits)
}

// runJobHeartbeat periodically checks the active queue lease and optionally
// refreshes a job lock. runOnce supplies a one-item loss channel and joins
// done after stopping this loop.
//
// An uncertain lease or lock read under a live context, or a false ownership
// result, marks loss once. The shared flag is set before loss notification and
// Process cancellation, so returned provider results can be rejected before
// recording. A closed stop channel or cancelled context ends the loop, with
// ticker cleanup and done publication deferred. Heartbeat timing has a
// one-second floor even when configured lock or stale durations are shorter.
func (w *CreativeRunWorker) runJobHeartbeat(ctx context.Context, runID, leaseToken string, lock CreativeRunJobLock, stop <-chan struct{}, done chan<- struct{}, leaseLost chan<- struct{}, cancel context.CancelFunc, leaseState *creativeLeaseState) {
	defer close(done)
	ticker := time.NewTicker(w.heartbeatInterval())
	defer ticker.Stop()
	var lost atomic.Bool
	// Publish the shared loss flag before notifying runOnce and cancelling its
	// Process context. The single buffered notification lets heartbeat exit while
	// the queue loop is still waiting for processing to return.
	markLost := func() {
		if lost.CompareAndSwap(false, true) {
			if leaseState != nil {
				leaseState.lost.Store(true)
			}
			leaseLost <- struct{}{}
			if cancel != nil {
				cancel()
			}
		}
	}
	for {
		select {
		case <-stop:
			return
		case <-ctx.Done():
			return
		case <-ticker.C:
			owned, err := w.queue.Heartbeat(ctx, runID, leaseToken)
			if err != nil && ctx.Err() == nil {
				w.warn("creative.worker_heartbeat_failed",
					"run_id", runID,
					"error", err,
				)
				// A failed heartbeat under a live context
				// leaves ownership uncertain. Mark
				// loss and cancel this processing context so
				// later context-aware storage
				// and transport operations stop using an
				// unconfirmed active lease.
				markLost()
				return
			} else if err == nil && !owned {
				w.warn("creative.worker_lease_lost",
					"run_id", runID,
				)
				markLost()
				return
			}
			if refresher, ok := lock.(CreativeRunJobLockRefresher); ok {
				owned, err := refresher.Refresh(ctx, w.opts.JobLockTTL)
				if err != nil && ctx.Err() == nil {
					w.warn("creative.worker_lock_refresh_failed",
						"run_id", runID,
						"error", err,
					)
					markLost()
					return
				} else if err == nil && !owned {
					w.warn("creative.worker_lock_lost",
						"run_id", runID,
					)
					markLost()
					return
				}
			}
		}
	}
}

// heartbeatInterval selects one third of the smaller stale-active and
// job-lock durations, with a one-second floor. Queue ownership and job-lock
// ownership expire independently, so the shorter configured lifetime controls
// the interval before that floor is applied.
//
// Positive subsecond options remain unchanged by normalization. For those
// lifetimes the floor can place the next refresh after expiry, so callers
// cannot infer that merely supplying positive options makes renewal early
// enough. The returned interval governs the shared queue and optional lock
// heartbeat loop.
func (w *CreativeRunWorker) heartbeatInterval() time.Duration {
	interval := min(w.opts.StaleActiveAfter, w.opts.JobLockTTL)
	interval /= 3
	// This floor can place refresh after a subsecond ownership expiry. Positive
	// options are retained by normalization, so callers choosing short durations
	// cannot assume a heartbeat precedes that expiry.
	if interval < time.Second {
		interval = time.Second
	}
	return interval
}

// MoveDueDelayedOnce delegates one due delayed batch using the normalized move
// limit. Missing worker or queue dependencies return zero successfully, while
// Redis transfer errors remain available to the caller.
func (w *CreativeRunWorker) MoveDueDelayedOnce(ctx context.Context) (int, error) {
	if w == nil || w.queue == nil {
		return 0, nil
	}
	return w.queue.MoveDueDelayedToReady(ctx, w.opts.DelayedMoveLimit)
}

// RunDelayedMover drains nonempty due batches immediately and waits after
// empty or failed batches until cancellation. Transfer errors are ignored by
// this loop so the next configured poll can retry available work.
func (w *CreativeRunWorker) RunDelayedMover(ctx context.Context) {
	if w == nil {
		return
	}
	for {
		if err := ctx.Err(); err != nil {
			return
		}
		// Treat transfer failure like an empty batch so the next
		// configured poll can
		// retry without spinning continuously on a store outage under the live
		// runtime context.
		moved, _ := w.MoveDueDelayedOnce(ctx)
		if moved > 0 {
			continue
		}
		sleepOrDone(ctx, w.opts.DelayedPollInterval)
	}
}

// RecoverStaleActiveOnce delegates one stale active batch using normalized age
// and count limits. Missing worker or queue returns zero successfully, while
// recovery errors remain available for the loop or caller.
func (w *CreativeRunWorker) RecoverStaleActiveOnce(ctx context.Context) (int, error) {
	if w == nil || w.queue == nil {
		return 0, nil
	}
	return w.queue.RecoverStaleActive(ctx, w.opts.StaleActiveAfter, w.opts.RecoverLimit)
}

// RunStaleActiveRecovery attempts stale recovery and waits for its interval
// until cancellation. Batch errors are ignored by this loop, leaving active
// entries eligible for a later timestamp-based recovery attempt.
func (w *CreativeRunWorker) RunStaleActiveRecovery(ctx context.Context) {
	if w == nil {
		return
	}
	for {
		if err := ctx.Err(); err != nil {
			return
		}
		// Recovery errors leave active timestamps eligible for a later scan. Keep
		// polling after the configured wait so store failure does not end this
		// recovery loop while cancellation still controls its lifetime.
		_, _ = w.RecoverStaleActiveOnce(ctx)
		sleepOrDone(ctx, w.opts.RecoveryInterval)
	}
}

// Options returns this nonnil worker normalized operating limits as a value
// copy. Callers can adjust that copy for constructing another worker without
// changing this worker stored durations or counts.
func (w *CreativeRunWorker) Options() CreativeWorkerOptions { return w.opts }

// warn passes event and attributes to the optional worker observer
// synchronously. Configure Observe before starting shared worker loops, and
// support concurrent callback invocations from independently processing tasks.
func (w *CreativeRunWorker) warn(event string, values ...any) {
	if w.ports.Observe != nil {
		w.ports.Observe(event, values...)
	}
}

// sleepOrDone waits for the timer duration or context cancellation and
// releases its timer afterward. It returns no completion flag, so polling
// callers recheck the context at the next loop entry.
func sleepOrDone(ctx context.Context, delay time.Duration) {
	timer := time.NewTimer(delay)
	defer timer.Stop()
	select {
	case <-ctx.Done():
	case <-timer.C:
	}
}

// RunOnce reserves and processes at most one task, then acknowledges or
// requeues its own active lease. This call has no drain channel and follows
// the shared context for cancellation and heartbeat lifetime.
func (w *CreativeRunWorker) RunOnce(ctx context.Context) error {
	return w.runOnce(ctx, nil)
}
