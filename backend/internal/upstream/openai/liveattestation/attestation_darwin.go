// attestation_darwin.go generates macOS Live attestation headers from
// DeviceCheck tokens and bounded host signals.
// macOS Live attestation uses the Node runtime and DeviceCheck native module
// found inside a ChatGPT application bundle. Runtime resolution requires Apple
// Silicon, checks the candidate bundle paths and module files, and reads an
// OpenAI-prefixed bundle identifier before generation runs.
//
// One five-second context bounds runtime lookup, device-signal collection, and
// the token-generation subprocess. The helper script receives a minimal
// environment containing the resolved module, bundle identifier, and bounded
// signal JSON; its embedded source defines the CBOR header representation.
// Locale, language, screen, and application-session values feed that
// representation, with byte caps and defaults preventing empty or unbounded
// signal values. The returned stdout must be bounded valid JSON before it can
// become an attestation header.

// Attestation constants select the system bundle and the shared generation budget;
// deviceCheckScript encodes the native token and supplied device signals for Live.
const (
	chatGPTApplicationPath = "/Applications/ChatGPT.app"
	attestationTimeout     = 5 * time.Second

	// deviceCheckScript generates a token with the ChatGPT App native module and encodes its CBOR payload.
	deviceCheckScript = `
const addon = require(process.env.TOKENROUTER_DEVICECHECK_MODULE);
const signals = JSON.parse(process.env.TOKENROUTER_ATTESTATION_SIGNALS);
const bundleID = process.env.TOKENROUTER_ATTESTATION_BUNDLE_ID;

function head(major, value) {
  if (value < 24) return Buffer.from([major + value]);
  if (value <= 255) return Buffer.from([major + 24, value]);
  if (value <= 65535) {
    const out = Buffer.allocUnsafe(3);
    out[0] = major + 25;
    out.writeUInt16BE(value, 1);
    return out;
  }
  const out = Buffer.allocUnsafe(5);
  out[0] = major + 26;
  out.writeUInt32BE(value, 1);
  return out;
}
function uint(value) { return head(0, value); }
function text(value) {
  const body = Buffer.from(value, "utf8");
  return Buffer.concat([head(96, body.length), body]);
}
function float(value) {
  if (Number.isSafeInteger(value) && value >= 0) return uint(value);
  const out = Buffer.allocUnsafe(9);
  out[0] = 251;
  out.writeDoubleBE(value, 1);
  return out;
}
function array(values) { return Buffer.concat([head(128, values.length), ...values]); }
function map(entries) {
  return Buffer.concat([head(160, entries.length), ...entries.flatMap(([key, value]) => [uint(key), value])]);
}
function field(key, value) { return Buffer.concat([text(key), text(value)]); }
function base64url(value) {
  return value.toString("base64").replaceAll("+", "-").replaceAll("/", "_").replace(/=+$/u, "");
}

(async () => {
  const result = await addon.generateToken();
  if (!result || !result.supported) throw new Error("DeviceCheck is not supported on this Mac");
  if (!result.tokenBase64) throw new Error("DeviceCheck returned no token");
  const fingerprint = map([
    [0, uint(signals.schemaVersion)],
    [1, array(signals.preferredLanguages.map(text))],
    [2, text(signals.locale)],
    [3, text(signals.timezone)],
    [4, uint(signals.screenSizeSum)],
    [5, float(signals.screenScale)],
    [6, text(signals.appSessionId)]
  ]);
  const fields = [
    field("token", result.tokenBase64),
    field("bundle_id", bundleID),
    Buffer.concat([text("f"), head(64, fingerprint.length), fingerprint])
  ];
  if (result.latencyMs != null) {
    fields.push(Buffer.concat([text("t"), float(result.latencyMs)]));
  }
  const token = "v1." + base64url(Buffer.concat([Buffer.from([160 + fields.length]), ...fields]));
  process.stdout.write(JSON.stringify({v: 1, s: 0, t: token}));
})().catch((error) => {
  process.stderr.write(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});`
)

// darwinProvider retains an application-session identity and candidate ChatGPT
// bundle paths.
type darwinProvider struct {
	// appSessionID is generated by NewProvider and reused across calls; readSignals
	// places that same bounded identity into each generated attestation
	// fingerprint.
	appSessionID string
	appPaths     []string // ordered candidate application paths
}

// deviceSignals contains bounded local values consumed by the DeviceCheck
// header script.
type deviceSignals struct {
	SchemaVersion      int      `json:"schemaVersion"`      // device fingerprint schema version
	PreferredLanguages []string `json:"preferredLanguages"` // bounded ordered language preferences
	Locale             string   `json:"locale"`             // host locale identifier
	Timezone           string   `json:"timezone"`           // host timezone identifier
	ScreenSizeSum      int      `json:"screenSizeSum"`      // rounded combined screen dimensions
	ScreenScale        float64  `json:"screenScale"`        // normalized screen backing scale
	AppSessionID       string   `json:"appSessionId"`       // bounded application session identifier
}

// macOSSignals holds the raw Foundation and AppKit values read through
// osascript.
type macOSSignals struct {
	// Locale and Timezone retain the raw host values here. readSignals bounds
	// and supplies defaults when constructing the separate deviceSignals fingerprint.
	Locale    string   `json:"locale"`    // host locale identifier
	Languages []string `json:"languages"` // raw host language preferences
	Timezone  string   `json:"timezone"`  // host timezone identifier
	Width     float64  `json:"width"`     // screen width in points
	Height    float64  `json:"height"`    // screen height in points
	Scale     float64  `json:"scale"`     // screen backing scale factor
}

// NewProvider creates a macOS provider with one random application-session ID.
// It searches the system ChatGPT path before the current user Applications path
// when a usable home directory is available.
func NewProvider() Provider {
	paths := []string{chatGPTApplicationPath}
	// Keep the system candidate when home lookup fails; the optional user path
	// broadens local discovery while the same bundle checks apply to the selected directory.
	if home, err := os.UserHomeDir(); err == nil && strings.TrimSpace(home) != "" {
		paths = append(paths, filepath.Join(home, "Applications", "ChatGPT.app"))
	}
	return &darwinProvider{
		appSessionID: uuid.NewString(),
		appPaths:     paths,
	}
}

// Check resolves local attestation prerequisites within the supplied context
// and five-second budget. It checks architecture, bundle files, and bundle
// identifier; generating a DeviceCheck token remains the separate Generate
// operation.
func (p *darwinProvider) Check(ctx context.Context) error {
	checkCtx, cancel := context.WithTimeout(ctx, attestationTimeout)
	// Release the bounded subprocess context when this operation returns so any
	// outstanding local process work cannot outlive its preflight or generation owner.
	defer cancel()
	_, _, _, err := p.resolveRuntime(checkCtx)
	return err
}

// resolveRuntime locates the bundled Node binary, native DeviceCheck module,
// and bundle identifier. It requires arm64 and a candidate application
// directory; existing non-directory module/runtime paths and an OpenAI-prefixed
// identifier pass the local checks.
func (p *darwinProvider) resolveRuntime(ctx context.Context) (string, string, string, error) {
	if runtime.GOARCH != "arm64" {
		return "", "", "", errors.New("live attestation currently requires Apple Silicon; Intel macOS is not supported")
	}
	appPath, err := p.findApplication()
	if err != nil {
		return "", "", "", err
	}
	resourcesPath := filepath.Join(appPath, "Contents", "Resources")
	nodePath := filepath.Join(resourcesPath, "cua_node", "bin", "node")
	modulePath := filepath.Join(resourcesPath, "native", "devicecheck.node")
	for filePath, label := range map[string]string{
		nodePath:   "bundled Node.js runtime",
		modulePath: "DeviceCheck native module",
	} {
		if info, statErr := os.Stat(filePath); statErr != nil || info.IsDir() {
			return "", "", "", fmt.Errorf("%w: ChatGPT app is missing its %s", ErrChatGPTAppMissing, label)
		}
	}
	bundleID, err := readBundleIdentifier(ctx, appPath)
	if err != nil {
		return "", "", "", err
	}
	return nodePath, modulePath, bundleID, nil
}

// Generate returns a bounded JSON attestation header from the ChatGPT
// DeviceCheck module. Its five-second context covers runtime resolution, macOS
// signal collection, and subprocess execution, and each failure returns before
// a header is delivered. The provider session identifier stays stable across
// calls.
//
// The subprocess receives resolved paths and marshalled signals through a
// minimal environment, while its embedded script creates the CBOR fingerprint
// and versioned token envelope. Failed stderr is bounded for diagnostics and an
// expired context receives a timeout-specific error. Successful stdout must
// meet the length bounds and JSON validity check; this validation does not
// inspect individual response fields.
func (p *darwinProvider) Generate(ctx context.Context) (string, error) {
	runCtx, cancel := context.WithTimeout(ctx, attestationTimeout)
	// Release the bounded subprocess context when this operation returns so any
	// outstanding local process work cannot outlive its preflight or generation owner.
	defer cancel()
	nodePath, modulePath, bundleID, err := p.resolveRuntime(runCtx)
	if err != nil {
		return "", err
	}
	signals, err := p.readSignals(runCtx)
	if err != nil {
		return "", err
	}
	signalsJSON, err := json.Marshal(signals)
	if err != nil {
		return "", fmt.Errorf("encode Live attestation signals: %w", err)
	}

	command := exec.CommandContext(runCtx, nodePath, "-e", deviceCheckScript)
	command.Env = []string{
		"PATH=/usr/bin:/bin",
		"TOKENROUTER_DEVICECHECK_MODULE=" + modulePath,
		"TOKENROUTER_ATTESTATION_BUNDLE_ID=" + bundleID,
		"TOKENROUTER_ATTESTATION_SIGNALS=" + string(signalsJSON),
	}
	var stdout bytes.Buffer
	var stderr bytes.Buffer
	command.Stdout = &stdout
	command.Stderr = &stderr
	if err := command.Run(); err != nil {
		if errors.Is(runCtx.Err(), context.DeadlineExceeded) {
			return "", errors.New("ChatGPT DeviceCheck token generation timed out")
		}
		reason := strings.TrimSpace(stderr.String())
		// Bound stderr exposed in the generation error while retaining the initial
		// diagnostic bytes from the failing native-module process for the caller.
		if len(reason) > 240 {
			reason = reason[:240]
		}
		if reason == "" {
			reason = err.Error()
		}
		return "", fmt.Errorf("ChatGPT DeviceCheck token generation failed: %s", reason)
	}
	header := strings.TrimSpace(stdout.String())
	// Check the serialized header envelope before it is used upstream; these
	// bounds reject missing or excessive output but do not validate token authenticity.
	if len(header) < 20 || len(header) > 16*1024 || !json.Valid([]byte(header)) {
		return "", errors.New("ChatGPT DeviceCheck returned a malformed attestation")
	}
	return header, nil
}

// findApplication returns the first candidate path that exists as a directory.
// Failed stat checks and non-directory candidates are skipped; exhausting the
// ordered list returns ErrChatGPTAppMissing for preflight or generation.
func (p *darwinProvider) findApplication() (string, error) {
	for _, appPath := range p.appPaths {
		// Skip unavailable candidates in search order so a missing system bundle
		// can still resolve to the user installation checked by the same runtime rules.
		info, err := os.Stat(appPath)
		if err == nil && info.IsDir() {
			return appPath, nil
		}
	}
	return "", ErrChatGPTAppMissing
}

// readBundleIdentifier asks plutil for the installed bundle identifier under
// ctx. Read failures wrap ErrChatGPTAppMissing and identifiers outside the
// com.openai prefix return an error before the native module is loaded.
func readBundleIdentifier(ctx context.Context, appPath string) (string, error) {
	infoPlist := filepath.Join(appPath, "Contents", "Info.plist")
	output, err := exec.CommandContext(
		ctx,
		"/usr/bin/plutil",
		"-extract",
		"CFBundleIdentifier",
		"raw",
		infoPlist,
	).Output()
	if err != nil {
		return "", fmt.Errorf("%w: cannot read its bundle identifier", ErrChatGPTAppMissing)
	}
	bundleID := strings.TrimSpace(string(output))
	if !strings.HasPrefix(bundleID, "com.openai.") {
		return "", errors.New("the installed ChatGPT app has an unexpected bundle identifier")
	}
	return bundleID, nil
}

// readSignals obtains and normalizes the device values passed to the
// attestation script. The supplied context bounds the osascript process, and
// unreadable or non-JSON output returns an error. Locale and timezone use
// bounded fallback values when missing.
//
// Preferred languages retain their supplied order, are limited to sixteen
// entries, and use locale for blank items or an absent list. Nonpositive screen
// scale becomes one, while width plus height is rounded to an integer and
// clamped nonnegative. The provider application-session ID is bounded
// separately, giving the CBOR script a consistent representation for every
// collected field.
func (p *darwinProvider) readSignals(ctx context.Context) (deviceSignals, error) {
	const script = `ObjC.import("Foundation"); ObjC.import("AppKit");
const screen = $.NSScreen.mainScreen;
const frame = screen.frame;
JSON.stringify({
  locale: ObjC.unwrap($.NSLocale.currentLocale.localeIdentifier),
  languages: ObjC.deepUnwrap($.NSLocale.preferredLanguages),
  timezone: ObjC.unwrap($.NSTimeZone.localTimeZone.name),
  width: Number(frame.size.width),
  height: Number(frame.size.height),
  scale: Number(screen.backingScaleFactor)
})`
	output, err := exec.CommandContext(ctx, "/usr/bin/osascript", "-l", "JavaScript", "-e", script).Output()
	if err != nil {
		return deviceSignals{}, fmt.Errorf("read macOS signals for Live attestation: %w", err)
	}
	var values macOSSignals
	if err := json.Unmarshal(output, &values); err != nil {
		return deviceSignals{}, fmt.Errorf("decode macOS signals for Live attestation: %w", err)
	}
	locale := truncateSignal(values.Locale, 64, "unknown")
	languages := values.Languages
	if len(languages) == 0 {
		languages = []string{locale}
	}
	// Cap language entries before individual normalization so the fingerprint
	// array stays bounded even when the host advertises a long preferred-language list.
	if len(languages) > 16 {
		languages = languages[:16]
	}
	for index := range languages {
		languages[index] = truncateSignal(languages[index], 64, locale)
	}
	scale := values.Scale
	if scale <= 0 {
		scale = 1
	}
	return deviceSignals{
		SchemaVersion:      1,
		PreferredLanguages: languages,
		Locale:             locale,
		Timezone:           truncateSignal(values.Timezone, 64, "unknown"),
		// Round the combined screen dimensions and clamp negative measurements.
		ScreenSizeSum: max(0, int(values.Width+values.Height+0.5)),
		ScreenScale:   scale,
		AppSessionID:  truncateSignal(p.appSessionID, 128, uuid.NewString()),
	}, nil
}

// truncateSignal trims a device-signal value, substitutes fallback when blank,
// and applies a byte cap. Callers provide a nonnegative limit; the result can
// end inside a multibyte character because truncation counts bytes.
func truncateSignal(value string, limit int, fallback string) string {
	value = strings.TrimSpace(value)
	if value == "" {
		value = fallback
	}
	if len(value) > limit {
		// Bound signal bytes before they enter the attestation fingerprint.
		return value[:limit]
	}
	return value
}
