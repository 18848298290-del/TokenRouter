// Passkey challenges are consumed before SDK parsing or verification, so
// malformed registration and rejected assertions cannot replay their Redis
// sessions. The PostgreSQL fixture persists a credential generated by a local
// software authenticator, then checks successful login's user identity,
// signature counter, and last-used timestamp.
//
// Registration builds WebAuthn authenticator bytes with the RP hash, presence
// and verification flags, a zero signature counter, and attested credential
// data containing a P-256 COSE public key. Login signs authenticator data
// together with the hash of clientDataJSON. Wrong-origin and altered-signature
// cases exercise rejection, while a valid signed assertion advances the stored
// counter from zero to one. This fixture exercises the installed SDK with local
// responses.

// TestPasskeySDKCeremony submits malformed, wrong-origin, altered-signature,
// and valid software-authenticator responses through PostgreSQL, Redis, and the
// SDK. Rejected sessions cannot replay, while valid login records the user,
// counter, and last-use time.
func TestPasskeySDKCeremony(t *testing.T) {
	integrationDB, integrationEntClient := identityDatabase(t)
	ctx := context.Background()
	client := integrationEntClient
	user := mustCreateUser(t, client, &identity.User{})
	users := identitypostgres.NewUserStore(client, integrationDB)
	repo := identitypostgres.NewPasskeyRepository(integrationDB)
	verifier, e := identityadapter.NewPasskeyVerifier(identityadapter.PasskeyOptions{Enabled: true, RPID: "example.com", RPDisplayName: "TEST", RPOrigins: []string{"https://example.com"}})
	require.NoError(t, e)
	core := identity.NewPasskeyService(true, verifier, repo, identityredis.NewPasskeySessionStore(rediscontainer.New(t)), users)
	encode := base64.RawURLEncoding.EncodeToString
	marshal := func(v any) []byte { b, e := json.Marshal(v); require.NoError(t, e); return b }
	// Reuse the malformed response session after its parsing failure to check that
	// consuming the Redis challenge precedes SDK parsing and prevents a second
	// attempt.
	_, broken, e := core.BeginRegistration(ctx, user.ID)
	require.NoError(t, e)
	_, e = core.FinishRegistration(ctx, user.ID, broken, "broken", bytes.NewBufferString("{"))
	require.ErrorIs(t, e, identity.ErrPasskeyVerify)
	_, e = core.FinishRegistration(ctx, user.ID, broken, "replay", bytes.NewBufferString("{"))
	require.ErrorIs(t, e, identity.ErrPasskeySession)
	creation, token, e := core.BeginRegistration(ctx, user.ID)
	require.NoError(t, e)
	private, e := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	require.NoError(t, e)
	// Encode the P-256 public coordinates as thirty-two-byte COSE values with EC2
	// key type and ES256 algorithm so the SDK can verify later signed assertions.
	public, e := cbor.Marshal(map[int]any{1: 2, 3: -7, -1: 1, -2: private.X.FillBytes(make([]byte, 32)), -3: private.Y.FillBytes(make([]byte, 32))})
	require.NoError(t, e)
	credentialID := []byte("test-local-software-authenticator")
	rpHash := sha256.Sum256([]byte("example.com"))
	// Start registration authenticator data with the RP hash and UP/UV/AT flags,
	// followed by the zero counter, sixteen-byte AAGUID, and big-endian credential
	// length.
	auth := append([]byte{}, rpHash[:]...)
	auth = append(auth, 0x45, 0, 0, 0, 0)
	auth = append(auth, make([]byte, 16)...)
	auth = binary.BigEndian.AppendUint16(auth, uint16(len(credentialID)))
	auth = append(auth, credentialID...)
	auth = append(auth, public...)
	attestation, e := cbor.Marshal(map[string]any{"fmt": "none", "attStmt": map[string]any{}, "authData": auth})
	require.NoError(t, e)
	clientData := marshal(map[string]any{"type": "webauthn.create", "challenge": creation.Response.Challenge, "origin": "https://example.com", "crossOrigin": false})
	registration := marshal(map[string]any{"id": encode(credentialID), "rawId": encode(credentialID), "type": "public-key", "response": map[string]any{"clientDataJSON": encode(clientData), "attestationObject": encode(attestation), "transports": []string{"internal"}}, "clientExtensionResults": map[string]any{"credProps": map[string]any{"rk": true}}})
	created, e := core.FinishRegistration(ctx, user.ID, token, "Local TEST", bytes.NewReader(registration))
	require.NoError(t, e)
	require.NotZero(t, created.ID)
	record, e := repo.GetByCredentialID(ctx, credentialID)
	require.NoError(t, e)
	require.Equal(t, uint32(0), record.Credential.Authenticator.SignCount)
	assert := func(origin string, valid bool) (string, []byte) {
		request, token, e := core.BeginLogin(ctx)
		require.NoError(t, e)
		data := marshal(map[string]any{"type": "webauthn.get", "challenge": request.Response.Challenge, "origin": origin, "crossOrigin": false})
		auth := append([]byte{}, rpHash[:]...)
		auth = append(auth, 0x05)
		auth = binary.BigEndian.AppendUint32(auth, 1)
		// Sign authenticator bytes plus SHA-256(clientDataJSON) with the fixture
		// private key, binding this assertion's RP, challenge, and origin to the
		// response signature.
		dataHash := sha256.Sum256(data)
		signed := append(append([]byte{}, auth...), dataHash[:]...)
		digest := sha256.Sum256(signed)
		sig, e := ecdsa.SignASN1(rand.Reader, private, digest[:])
		require.NoError(t, e)
		// Alter a signature byte after signing to retain the response structure while
		// submitting a signature that the SDK should reject for this generated
		// credential.
		if !valid {
			sig[len(sig)-1] ^= 1
		}
		return token, marshal(map[string]any{"id": encode(credentialID), "rawId": encode(credentialID), "type": "public-key", "response": map[string]any{"clientDataJSON": encode(data), "authenticatorData": encode(auth), "signature": encode(sig), "userHandle": encode(record.UserHandle)}})
	}
	for _, sample := range []struct {
		// name identifies rejection case; origin supplies the client RP origin.
		name, origin string
		// valid controls signature corruption. False flips a generated signature byte
		// before serialization so the SDK receives an altered proof for this
		// credential.
		valid bool
	}{{"origin", "https://wrong.example", true}, {"signature", "https://example.com", false}} {
		t.Run(sample.name, func(t *testing.T) {
			token, body := assert(sample.origin, sample.valid)
			_, e := core.FinishLogin(ctx, token, bytes.NewReader(body))
			require.ErrorIs(t, e, identity.ErrPasskeyVerify)
			_, e = core.FinishLogin(ctx, token, bytes.NewReader(body))
			require.ErrorIs(t, e, identity.ErrPasskeySession)
		})
	}
	login, body := assert("https://example.com", true)
	got, e := core.FinishLogin(ctx, login, bytes.NewReader(body))
	require.NoError(t, e)
	require.Equal(t, user.ID, got.ID)
	record, e = repo.GetByCredentialID(ctx, credentialID)
	require.NoError(t, e)
	require.Equal(t, uint32(1), record.Credential.Authenticator.SignCount)
	require.NotNil(t, record.LastUsedAt)
	_, e = core.FinishLogin(ctx, login, bytes.NewReader(body))
	require.ErrorIs(t, e, identity.ErrPasskeySession)
}
