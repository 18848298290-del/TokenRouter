<template>
  <div class="group/usage relative text-sm">
    <div class="flex items-center gap-1.5">
      <span class="text-gray-500 dark:text-gray-400">{{ t('admin.users.today') }}:</span>
      <span class="font-medium text-gray-900 dark:text-white">{{
        formatBalanceAmount(today, { fractionDigits: 4 })
      }}</span>
      <Icon
        v-if="hasBreakdown"
        name="infoCircle"
        size="xs"
        class="text-gray-400 dark:text-gray-500"
      />
    </div>
    <div class="mt-0.5 flex items-center gap-1.5">
      <span class="text-gray-500 dark:text-gray-400">{{ t('admin.users.total') }}:</span>
      <span class="font-medium text-gray-900 dark:text-white">{{
        formatBalanceAmount(total, { fractionDigits: 4 })
      }}</span>
    </div>

    <div
      v-if="hasBreakdown"
      class="pointer-events-none absolute left-full top-0 z-50 ml-2 min-w-[220px] whitespace-nowrap tooltip-panel rounded-control px-3 py-2 text-xs opacity-0 shadow-xl transition-opacity duration-fast group-hover/usage:opacity-100"
    >
      <div
        class="mb-1.5 flex items-center justify-between gap-3 border-b border-white/10 pb-1 text-xs opacity-80"
      >
        <span>{{ t('admin.users.platformBreakdown') }}</span>
        <span class="font-mono">{{ t('admin.users.today') }} / {{ t('admin.users.total') }}</span>
      </div>
      <div
        v-for="item in sortedBreakdown"
        :key="item.platform"
        class="flex items-center justify-between gap-3 py-0.5"
        :class="{ 'opacity-70 italic': item.isOther }"
      >
        <span class="capitalize">
          {{ item.isOther ? t('admin.users.platformOther') : usagePlatformLabel(item.platform) }}
        </span>
        <span class="font-mono">
          {{ formatBalanceAmount(item.today_actual_cost, { fractionDigits: 4 }) }}
          <span class="opacity-50">/</span>
          {{ formatBalanceAmount(item.total_actual_cost, { fractionDigits: 4 }) }}
        </span>
      </div>
    </div>
  </div>
</template>

<script setup lang="ts">
import { computed } from 'vue'
import { useI18n } from 'vue-i18n'
import Icon from '@/components/icons/Icon.vue'
import type { PlatformUsage } from '@/api/admin/dashboard'
import { useBalanceDisplay } from '@/composables/useBalanceDisplay'
import { usagePlatformLabel } from '@/utils/platformColors'

// PlatformUsageBreakdown.vue reconciles platform cost rows with displayed daily and
// lifetime totals. Platform records are copied and sorted by lifetime charge before
// rendering, so display ordering does not mutate the parent array. The summary can include
// spending whose platform has no individual entry.
//
// Daily and lifetime differences are calculated independently and clamped at zero. When
// either positive difference exceeds the display tolerance, one Other row carries both
// differences. This keeps unassigned charges visible while leaving overcounted platform
// data unchanged; negative balancing adjustments are not generated by this component.

// props supplies parent-owned daily and lifetime totals together with the optional platform
// cost breakdown.
const props = defineProps<{
  today: number // aggregate charge for today
  total: number // aggregate lifetime charge
  // byPlatform supplies parent-owned cost rows; sortedBreakdown copies the array
  // before sorting, then copies row objects before adding residual display data.
  byPlatform?: PlatformUsage[]
}>()

// Translation and balance formatting supply tooltip labels and monetary presentation for
// the copied platform rows.
const { t } = useI18n()
const { formatBalanceAmount } = useBalanceDisplay()

// OTHER_THRESHOLD ignores residual costs at or below one ten-thousandth when deciding
// whether an Other row is useful.
const OTHER_THRESHOLD = 0.0001

// BreakdownRow pairs daily and lifetime charges with a platform display identity.
interface BreakdownRow {
  platform: string // platform display identity
  today_actual_cost: number // actual charge for today
  total_actual_cost: number // actual lifetime charge
  // isOther marks the synthetic residual row so the template translates its label instead
  // of resolving a platform name.
  isOther?: boolean
}

// sortedBreakdown copies platform records and orders them by lifetime charge. It then
// compares the daily and lifetime sums with their respective supplied totals, treating
// negative differences as zero.
//
// Either residual exceeding OTHER_THRESHOLD adds a shared Other row containing both
// residual amounts. The two totals can differ independently, so testing only lifetime
// spending would omit a daily remainder. Parent records retain their array order and field
// values throughout this display calculation.
const sortedBreakdown = computed<BreakdownRow[]>(() => {
  const list = props.byPlatform ?? []
  const rows: BreakdownRow[] = [...list]
    .sort((a, b) => b.total_actual_cost - a.total_actual_cost)
    .map((p) => ({ ...p }))

  const sumTotal = rows.reduce((s, r) => s + r.total_actual_cost, 0)
  const sumToday = rows.reduce((s, r) => s + r.today_actual_cost, 0)
  // Clamp each remainder independently because an overcount in one total must not create a
  // negative balancing charge in the tooltip.
  const diffTotal = Math.max(0, props.total - sumTotal)
  const diffToday = Math.max(0, props.today - sumToday)
  if (diffTotal > OTHER_THRESHOLD || diffToday > OTHER_THRESHOLD) {
    rows.push({
      platform: '__other__',
      today_actual_cost: diffToday,
      total_actual_cost: diffTotal,
      isOther: true,
    })
  }
  return rows
})

// hasBreakdown reports whether platform or residual rows exist for the cost details
// tooltip.
const hasBreakdown = computed(() => sortedBreakdown.value.length > 0)
</script>
